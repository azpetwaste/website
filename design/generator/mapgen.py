def d(g, close=True):
    def ring(coords):
        pts = list(coords)
        if close and pts[0] == pts[-1]:
            pts = pts[:-1]
        s = 'M%s' % ' '.join('%g %g' % (round(x, 1), round(y, 1)) for x, y in pts[:1])
        s += 'L' + ' '.join('%g %g' % (round(x, 1), round(y, 1)) for x, y in pts[1:])
        return s + ('Z' if close else '')
    gs = g.geoms if hasattr(g, 'geoms') else [g]
    out = []
    for p in gs:
        if p.geom_type != 'Polygon' or p.area < 4:
            continue
        out.append(ring(p.exterior.coords))
        out.extend(ring(i.coords) for i in p.interiors if Polygon(i).area > 30)
    return ''.join(out)


